#!/usr/bin/env python3
"""Helpers shared by the Launchpad MFC scripts (runmfc.sh, mfccheck.py,
mfc_autotune.py). Also a small CLI used by runmfc.sh:

    mfclib.py resolve CASE                  -> "<abs case.py>\\t<slug>\\t<json args>\\t<steps_param 0|1>"
    mfclib.py examples                      -> every examples/ directory name, one per line
    mfclib.py wrap RUN_DIR CASE_PY RANKS OVERRIDES_JSON
    mfclib.py result RUN_DIR STATUS META_JSON   (prints the MFC_RESULT line)

Every run of runmfc.sh leaves RUN_DIR/result.json with its configuration and
timings; ``load_results()`` reads them back.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
MFC_DIR = REPO / "libs" / "clone" / "MFC"
CASES_FILE = HERE / "cases.yaml"
RUNS_DIR = REPO / "outputs" / "mfc_runs"

#: Prefix of the one-line JSON summary runmfc.sh prints at the end of a run.
RESULT_TAG = "MFC_RESULT "


EXAMPLES_DIR = MFC_DIR / "examples"


def steps_by_param(case: str) -> bool:
    """True for a cases.yaml entry marked `steps: param` or any case in MFC's
    examples/: the case script has no --steps argument, so runmfc.sh sets the
    step count through t_step_start/stop/save overrides instead."""
    for entry in yaml.safe_load(CASES_FILE.read_text()) or []:
        if entry["slug"] == case:
            return entry.get("steps") == "param"
    path = resolve_case(case)[0]
    return EXAMPLES_DIR.resolve() in path.parents


def example_slugs() -> list[str]:
    """Every directory of MFC's examples/ that has a case.py."""
    return sorted(p.parent.name for p in EXAMPLES_DIR.glob("*/case.py"))


def resolve_case(case: str) -> tuple[Path, str, list[str]]:
    """A case.py path, a slug from cases.yaml, or the name of a directory in
    MFC's examples/ -> (absolute path, slug, fixed args)."""
    p = Path(case).expanduser()
    if p.is_file():
        p = p.resolve()
        slug = p.parent.name if p.name == "case.py" else p.stem
        return p, slug, []
    for entry in yaml.safe_load(CASES_FILE.read_text()) or []:
        if entry["slug"] == case:
            path = Path(entry["path"])
            path = path if path.is_absolute() else MFC_DIR / path
            if not path.is_file():
                raise SystemExit(f"cases.yaml: {case}: {path} does not exist")
            return path.resolve(), case, [str(a) for a in entry.get("args") or []]
    example = EXAMPLES_DIR / case / "case.py"
    if example.is_file():
        return example.resolve(), case, []
    slugs = [e["slug"] for e in yaml.safe_load(CASES_FILE.read_text()) or []]
    raise SystemExit(f"unknown case '{case}': not a file, not an examples/ directory, and not one of {slugs}")


_WRAPPER = '''#!/usr/bin/env python3
# Generated by scripts/Launchpad/mfc/runmfc.sh. MFC runs a case in the
# directory of its case file, so this stand-in lives in the run directory:
# it runs the real case with the same arguments and applies OVERRIDES.
import json
import os
import subprocess
import sys

ORIGINAL = {original!r}
OVERRIDES = {overrides!r}
RANKS = {ranks!r}

argv = sys.argv[1:]
if "--mfc" in argv:
    # `mfc.sh build` does not pass the rank layout; benchmark cases need it.
    i = argv.index("--mfc") + 1
    state = json.loads(argv[i])
    state.setdefault("nodes", 1)
    state.setdefault("tasks_per_node", RANKS)
    argv[i] = json.dumps(state)
out = subprocess.run([sys.executable, ORIGINAL] + argv, cwd=os.path.dirname(ORIGINAL),
                     check=True, capture_output=True, text=True).stdout
case = json.loads(out)
case.update(OVERRIDES)
print(json.dumps(case))
'''


def write_wrapper(run_dir: Path, case_py: Path, ranks: int, overrides: dict[str, Any]) -> Path:
    run_dir.mkdir(parents=True, exist_ok=True)
    path = run_dir / "case.py"
    path.write_text(_WRAPPER.format(original=str(case_py.resolve()), overrides=overrides, ranks=ranks))
    return path


def parse_summary(path: Path) -> dict[str, Any]:
    """MFC's --output-summary YAML: {target: {exec: s, grind: ns/gp/eq/rhs}},
    plus invocation/lock entries that are skipped."""
    if not path.is_file():
        return {}
    try:
        data = yaml.safe_load(path.read_text()) or {}
    except yaml.YAMLError:
        return {}
    out: dict[str, Any] = {}
    for target, vals in data.items():
        if target in ("invocation", "lock") or not isinstance(vals, dict):
            continue
        for key, value in vals.items():
            try:
                out[f"{target}_{key}"] = float(value)
            except (TypeError, ValueError):
                pass
    return out


def parse_log(text: str) -> dict[str, Any]:
    """Figures simulation prints to stdout (used when the summary is missing)."""
    out: dict[str, Any] = {}
    m = re.findall(r"Performance:\s*([0-9.eE+-]+)\s*ns/gp/eq/rhs", text)
    if m:
        out["simulation_grind"] = float(m[-1])
    return out


def write_result(run_dir: Path, status: str, meta: dict[str, Any]) -> dict[str, Any]:
    timings = parse_summary(run_dir / "summary.yaml")
    log = run_dir / "mfc.log"
    if "simulation_grind" not in timings and log.is_file():
        timings.update(parse_log(log.read_text(errors="replace")))
    result = dict(meta)
    result["status"] = status
    result["grind_ns"] = timings.get("simulation_grind")
    result["sim_exec_s"] = timings.get("simulation_exec")
    result["pre_exec_s"] = timings.get("pre_process_exec")
    if status == "ok" and result["grind_ns"] is None:
        result["status"] = "no_result"
    (run_dir / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def load_results(root: Path = RUNS_DIR) -> list[dict[str, Any]]:
    """Every result.json under ``root`` (recursively), oldest first."""
    results = []
    for path in sorted(root.rglob("result.json")):
        try:
            rec = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        rec.setdefault("run_dir", str(path.parent))
        results.append(rec)
    results.sort(key=lambda r: r.get("timestamp_utc") or "")
    return results


def config_tag(r: dict[str, Any]) -> str:
    """Short label for a run's build/run configuration."""
    parts = [r.get("precision", "double")]
    if r.get("case_opt"):
        parts.append("caseopt")
    if r.get("fastmath"):
        parts.append("fastmath")
    if r.get("rdma_mpi"):
        parts.append("rdma")
    parts.append(f"bind={r.get('bind', 'none')}")
    parts.append(f"n{r.get('ranks')}")
    return " ".join(parts)


def _main(argv: list[str]) -> int:
    cmd, args = argv[0], argv[1:]
    if cmd == "resolve":
        path, slug, fixed = resolve_case(args[0])
        print(f"{path}\t{slug}\t{json.dumps(fixed)}\t{int(steps_by_param(slug))}")
    elif cmd == "examples":
        print("\n".join(example_slugs()))
    elif cmd == "wrap":
        write_wrapper(Path(args[0]), Path(args[1]), int(args[2]), json.loads(args[3]))
    elif cmd == "result":
        result = write_result(Path(args[0]), args[1], json.loads(args[2]))
        print(RESULT_TAG + json.dumps(result, sort_keys=True))
        return 0 if result["status"] == "ok" else 1
    else:
        raise SystemExit(f"unknown command {cmd}")
    return 0


if __name__ == "__main__":
    sys.exit(_main(sys.argv[1:]))
